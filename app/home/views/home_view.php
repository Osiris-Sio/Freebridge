<h1>Culture et Histoire du Bridge</h1>

<article>
    <header>
        <h2>Les origines dans le monde</h2>
    </header>

    <img src="assets/img/bridge_history.jpg" alt="Photo historique du bridge" class="centered-img history-img">
    <p>Le bridge tire ses origines du <strong>Whist</strong>, un jeu de cartes anglais du 16ème siècle. À la fin du 19ème siècle, une variante appelée <em>Biritch</em> (ou Whist Russe) fait son apparition. Mais c'est en 1925 que le jeu moderne, le <strong>Bridge Contrat</strong>, voit le jour grâce à l'homme d'affaires américain Harold Stirling Vanderbilt, qui en perfectionne le système de marque de manière brillante lors d'une croisière.</p>
</article>

<article>
    <header>
        <h2>Le bridge en France</h2>
    </header>
    <p>La France a joué un rôle déterminant dans l'évolution de ce jeu. Dès 1918, une variante nommée le <em>Plafond</em> y connaît un immense succès et a servi de transition naturelle vers le bridge moderne. La Commission Française de Bridge a d'ailleurs activement participé à la standardisation mondiale des règles dans les années 1920.</p>
</article>

